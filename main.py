@app.post("/api/discovery/run", tags=["Discovery"])
def run_discovery(payload: DiscoveryRun):
    if not payload.consent_confirmed:
        raise HTTPException(400, "Explicit consent is required before any source is queried.")
    if not (payload.use_gmail or payload.use_public_web or payload.use_breach_check):
        raise HTTPException(400, "Select at least one discovery source.")
    results: list = []
    errors: list = []
    phone = (payload.phone_number or "").strip()
    email = (payload.email_address or "").strip().lower()

    if payload.use_gmail:
        token = _refresh_gmail_token()
        if not token:
            errors.append({
                "source": "Gmail",
                "status": "not_connected",
                "message": "Connect Gmail first via the Connect Gmail button.",
            })
        else:
            try:
                q = 'newer_than:10y {registration registered "verify your account" "welcome to" "phone number" mobile contact}'
                url = "https://gmail.googleapis.com/gmail/v1/users/me/messages?maxResults=50&q=" + urllib.parse.quote(q)
                listing = _http_json(url, {"Authorization": "Bearer " + token})
                for item in listing.get("messages", [])[:50]:
                    msg = _http_json(
                        "https://gmail.googleapis.com/gmail/v1/users/me/messages/"
                        + urllib.parse.quote(item["id"])
                        + "?format=metadata&metadataHeaders=From&metadataHeaders=Subject&metadataHeaders=Date",
                        {"Authorization": "Bearer " + token},
                    )
                    headers = {h.get("name", "").lower(): h.get("value", "") for h in msg.get("payload", {}).get("headers", [])}
                    results.append({
                        "source": "Gmail registration evidence",
                        "kind": "email_match",
                        "title": headers.get("subject", "(no subject)")[:180],
                        "publisher": headers.get("from", "(unknown)")[:180],
                        "url": None,
                        "date": headers.get("date"),
                        "evidence": msg.get("snippet", "")[:260],
                        "confidence": "medium",
                        "confidence_reason": "Message matched registration-oriented search terms. Manual review needed.",
                        "provenance": "Gmail API metadata + snippet. Session-only, not stored.",
                    })
                if not listing.get("messages"):
                    errors.append({
                        "source": "Gmail",
                        "status": "no_matches",
                        "message": "No messages matched. Not proof no account exists.",
                    })
            except Exception:
                errors.append({
                    "source": "Gmail",
                    "status": "provider_error",
                    "message": "Gmail search failed or rate-limited. No content saved.",
                })

    if payload.use_public_web:
        if not phone:
            errors.append({
                "source": "Public web",
                "status": "missing_input",
                "message": "Enter a phone number for public-web search.",
            })
        elif not (env_ready("GOOGLE_CSE_API_KEY") and env_ready("GOOGLE_CSE_CX")):
            errors.append({
                "source": "Public web",
                "status": "not_configured",
                "message": "Set GOOGLE_CSE_API_KEY and GOOGLE_CSE_CX. No query sent.",
            })
        else:
            try:
                url = "https://www.googleapis.com/customsearch/v1?" + urllib.parse.urlencode({
                    "key": os.environ["GOOGLE_CSE_API_KEY"],
                    "cx": os.environ["GOOGLE_CSE_CX"],
                    "q": '"' + phone + '"',
                    "num": 10,
                })
                data = _http_json(url, {"Accept": "application/json"})
                for item in data.get("items", [])[:10]:
                    results.append({
                        "source": "Public web search",
                        "kind": "public_page",
                        "title": item.get("title", "Untitled")[:220],
                        "publisher": urllib.parse.urlparse(item.get("link", "")).netloc,
                        "url": item.get("link"),
                        "date": None,
                        "evidence": item.get("snippet", "")[:400],
                        "confidence": "low",
                        "confidence_reason": "Search snippet only. Verify manually; stale or false matches are common.",
                        "provenance": "Google Programmable Search. URL and snippet from provider.",
                    })
                if not data.get("items"):
                    errors.append({
                        "source": "Public web",
                        "status": "no_matches",
                        "message": "No indexed results found.",
                    })
            except Exception:
                errors.append({
                    "source": "Public web",
                    "status": "provider_error",
                    "message": "Search provider failed or quota exceeded.",
                })

    if payload.use_breach_check:
        if not email:
            errors.append({
                "source": "Breach check",
                "status": "missing_input",
                "message": "Enter an email address for HIBP lookup.",
            })
        elif not env_ready("HIBP_API_KEY"):
            errors.append({
                "source": "Breach check",
                "status": "not_configured",
                "message": "Set HIBP_API_KEY. No lookup sent.",
            })
        else:
            try:
                url = "https://haveibeenpwned.com/api/v3/breachedaccount/" + urllib.parse.quote(email, safe="") + "?truncateResponse=false"
                data = _http_json(
                    url,
                    {
                        "hibp-api-key": os.environ["HIBP_API_KEY"],
                        "user-agent": "NumberShield/1.0",
                        "Accept": "application/json",
                    },
                )
                for item in (data if isinstance(data, list) else []):
                    results.append({
                        "source": "Have I Been Pwned",
                        "kind": "breach_record",
                        "title": item.get("Name", "Named breach"),
                        "publisher": item.get("Domain", "HIBP"),
                        "url": "https://haveibeenpwned.com/",
                        "date": item.get("BreachDate"),
                        "evidence": "Exposed data classes: " + ", ".join(item.get("DataClasses", [])[:12]),
                        "confidence": "medium",
                        "confidence_reason": "Provider reports email in breach; does not establish phone number was included.",
                        "provenance": "Have I Been Pwned API v3.",
                    })
                if not data:
                    errors.append({
                        "source": "Breach check",
                        "status": "no_matches",
                        "message": "HIBP returned no breach records. Coverage is incomplete.",
                    })
            except urllib.error.HTTPError as exc:
                m = {
                    404: ("no_matches", "HIBP: no records for this email."),
                    401: ("auth_error", "HIBP rejected API key."),
                    429: ("rate_limited", "HIBP rate limit. Try later."),
                }
                s, msg = m.get(exc.code, ("provider_error", f"HIBP failed (HTTP {exc.code})."))
                errors.append({"source": "Breach check", "status": s, "message": msg})
            except Exception:
                errors.append({
                    "source": "Breach check",
                    "status": "provider_error",
                    "message": "HIBP lookup failed. Identifier not stored.",
                })

    return {
        "results": results,
        "errors": errors,
        "result_count": len(results),
        "generated_at": now(),
        "persistence": "Results and identifiers NOT saved to database or audit log.",
        "limitations": [
            "Evidence discovery only, not a complete inventory.",
            "Gmail search finds clues; cannot enumerate every account.",
            "Public search sees indexed pages only.",
            "HIBP checks email addresses, not phone numbers.",
            "Confidence describes evidence usefulness, not probability of harm.",
        ],
    }

