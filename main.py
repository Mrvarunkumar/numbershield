@app.get("/api/discovery/gmail/connect", tags=["Discovery"])
def gmail_connect():
    if not all(env_ready(k) for k in ("GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET", "GOOGLE_REDIRECT_URI")):
        raise HTTPException(
            503,
            "Gmail OAuth not configured. Set GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET, GOOGLE_REDIRECT_URI.",
        )
    state = secrets.token_urlsafe(24)
    OAUTH_STATES[state] = time.time() + 600
    params = urllib.parse.urlencode({
        "client_id": os.environ["GOOGLE_CLIENT_ID"],
        "redirect_uri": os.environ["GOOGLE_REDIRECT_URI"],
        "response_type": "code",
        "scope": "https://www.googleapis.com/auth/gmail.readonly",
        "access_type": "offline",
        "prompt": "consent",
        "state": state,
    })
    return RedirectResponse("https://accounts.google.com/o/oauth2/v2/auth?" + params, status_code=302)

@app.get("/api/discovery/gmail/callback", tags=["Discovery"])
def gmail_callback(code: Optional[str] = None, state: Optional[str] = None, error: Optional[str] = None):
    if error:
        raise HTTPException(400, "Google authorization was cancelled or denied.")
    expiry = OAUTH_STATES.pop(state or "", None)
    if not expiry or expiry < time.time() or not code:
        raise HTTPException(400, "OAuth state expired or invalid. Restart Gmail connection.")
    payload = urllib.parse.urlencode({
        "code": code,
        "client_id": os.environ["GOOGLE_CLIENT_ID"],
        "client_secret": os.environ["GOOGLE_CLIENT_SECRET"],
        "redirect_uri": os.environ["GOOGLE_REDIRECT_URI"],
        "grant_type": "authorization_code",
    }).encode()
    try:
        data = _http_json(
            "https://oauth2.googleapis.com/token",
            {"Content-Type": "application/x-www-form-urlencoded"},
            payload,
            "POST",
        )
    except Exception:
        raise HTTPException(502, "Could not complete Google OAuth token exchange.")
    GMAIL_TOKEN.clear()
    GMAIL_TOKEN.update({
        "access_token": data.get("access_token"),
        "refresh_token": data.get("refresh_token"),
        "expires_at": time.time() + int(data.get("expires_in", 3600)),
    })
    return RedirectResponse("/?gmail=connected#discovery", status_code=303)

