@app.post("/api/requests", status_code=201, tags=["Privacy Requests"])
def create_request(payload: RequestCreate):
    db = get_db()
    svc = db.get_service_by_id(payload.service_id)
    if not svc:
        raise HTTPException(404, "Service not found")
    ref = "NS-" + "".join(secrets.choice(string.ascii_uppercase + string.digits) for _ in range(8))
    text = draft_for(svc["name"], payload.request_type, ref)
    rec = db.create_request(payload.service_id, payload.request_type, ref, text)
    if not rec:
        raise HTTPException(500, "Failed to create privacy request")
    return {
        "id": rec["id"],
        "service_name": svc["name"],
        "request_type": payload.request_type,
        "status": "draft",
        "reference": ref,
        "draft_text": text,
        "created_at": rec["created_at"],
        "message": "Draft created in Supabase. It has NOT been sent to the external service.",
    }

